"""
pynet2plan.eon.traffic
=====================

EON demands are ordinary :class:`pynet2plan.traffic.Demand` objects whose
``traffic`` is a data rate in **Gb/s** (100, 200, ..., 800): the same CSV
files, loaded with :func:`pynet2plan.traffic.load_traffic`.

Random demands draw the data rate among the rates of the transponder table
(uniformly), as in the EON notebook::

    from pynet2plan.eon.traffic import random_eon_traffic
    demands = random_eon_traffic(G, 120, rates=[100, 200, ..., 800], seed=42)

The generator is numpy's ``default_rng(seed)``: the same seed and the same
network (same node order) give the same demands on every computer, and the
same demands as the notebook (``make_demands`` with ``default_rng(42)``).
"""

from __future__ import annotations

import os
import re
from typing import Iterable

import numpy as np

from ..errors import TrafficError
from ..traffic import Demand, read_traffic_file


def _check(G, rates):
    nodes = list(G.nodes)
    if len(nodes) < 2:
        raise TrafficError("At least 2 nodes are needed to create demands.")
    rates = sorted({int(r) for r in rates})
    if not rates or rates[0] <= 0:
        raise TrafficError("Give at least one positive data rate (Gb/s).")
    return nodes, rates


def random_eon_traffic(G, num_demands: int, rates, seed: int = 0,
                       allow_duplicate_pairs: bool = True) -> list:
    """``num_demands`` demands between random distinct nodes, data rate drawn
    uniformly from ``rates`` (Gb/s). Without duplicates at most N(N-1)."""
    nodes, rates = _check(G, rates)
    if num_demands < 0:
        raise TrafficError("The number of demands cannot be negative.")
    rng = np.random.default_rng(int(seed))
    out = []
    if allow_duplicate_pairs:
        for i in range(int(num_demands)):
            s, t = rng.choice(len(nodes), size=2, replace=False)
            out.append(Demand(i, nodes[int(s)], nodes[int(t)], int(rng.choice(rates))))
        return out
    pairs = [(a, b) for a in nodes for b in nodes if a != b]
    order = rng.permutation(len(pairs))[:min(int(num_demands), len(pairs))]
    for i, k in enumerate(order):
        a, b = pairs[int(k)]
        out.append(Demand(i, a, b, int(rng.choice(rates))))
    return out


def full_mesh_eon_traffic(G, rates, seed: int = 0) -> list:
    """One demand per ordered node pair, data rate drawn from ``rates``."""
    nodes, rates = _check(G, rates)
    rng = np.random.default_rng(int(seed))
    out = []
    for a in nodes:
        for b in nodes:
            if a != b:
                out.append(Demand(len(out), a, b, int(rng.choice(rates))))
    return out


def generation_comment(kind: str, **params) -> str:
    args = ", ".join(f"{k}={v!r}" for k, v in params.items())
    return f"generated by pynet2plan.eon.traffic.{kind}({args})"


def by_rate(demands) -> dict:
    """``{rate: number of demands}``"""
    out: dict = {}
    for d in demands:
        out[d.traffic] = out.get(d.traffic, 0) + 1
    return dict(sorted(out.items()))


# ----------------------------------------------------------------------
# Traffic and topology files that go together
# ----------------------------------------------------------------------
def find_traffic_for(topology_path: str, traffic_dir: str, suffixes=("_traffic",)) -> str | None:
    """The traffic file shipped with a topology: ``<stem><suffix>.csv`` in
    ``traffic_dir`` or one of its sub-folders (``data/traffic/real/``), trying
    the ``suffixes`` in order; ``None`` if there is none."""
    stem = os.path.splitext(os.path.basename(topology_path))[0]
    for suffix in suffixes:
        name = (stem + suffix + ".csv").lower()
        for dirpath, _, files in sorted(os.walk(traffic_dir)):
            for f in files:
                if f.lower() == name:
                    return os.path.join(dirpath, f)
    return None


def find_topology_for(path: str, search_dirs: Iterable[str]) -> str | None:
    """The topology file (``*.json`` under ``search_dirs``) whose nodes include
    every node of the traffic file ``path``, or ``None``.

    Used when a traffic file does not fit the open network. Preference: the
    topology named in a ``# topology: ... (data/....json)`` comment, then a
    topology whose name starts the file name (``nsfnet14`` for
    ``nsfnet14_eon_traffic.csv``), then the smallest network that fits.
    """
    from ..network import load_topology
    try:
        tf = read_traffic_file(path)
    except TrafficError:
        return None
    needed = {d.origin for d in tf.demands} | {d.destination for d in tf.demands}
    if not needed:
        return None
    root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    named = set()
    for c in tf.comments:
        m = re.search(r"\(([^()]+\.json)\)\s*$", c)
        if m:
            named.add(os.path.normcase(os.path.abspath(os.path.join(root, m.group(1)))))
    stem = os.path.splitext(os.path.basename(path))[0].lower()
    best = None
    for d in search_dirs:
        for dirpath, _, files in os.walk(d):
            for f in files:
                if not f.lower().endswith(".json"):
                    continue
                cand = os.path.join(dirpath, f)
                try:
                    H = load_topology(cand)
                except Exception:  # noqa: BLE001 - not a topology: skip it
                    continue
                if not needed <= set(H.nodes):
                    continue
                topo_stem = os.path.splitext(f)[0].lower()
                key = (os.path.normcase(os.path.abspath(cand)) not in named,
                       not stem.startswith(topo_stem + "_"), H.number_of_nodes(), cand)
                if best is None or key < best:
                    best = key
    return best[-1] if best else None


